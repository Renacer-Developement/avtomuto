export async function getBlogPosts(): Promise<BlogPost[]> {
  const data = await hygraphFetch<{ blogPosts: { slug: string; title: string; excerpt: string; date: string; relatedServiceSlug?: string; content: { html: string } }[] }>(`
    query BlogPosts {
      blogPosts(orderBy: date_DESC) {
        slug
        title
        excerpt
        date
        relatedServiceSlug
        content { html }
      }
    }
  `);

  if (data?.blogPosts?.length) {
    return data.blogPosts.map((p) => ({ ...p, content: p.content.html }));
  }

  return FALLBACK_POSTS;
}

export async function getPostBySlug(slug: string): Promise<BlogPost | undefined> {
  const posts = await getBlogPosts();
  return posts.find((p) => p.slug === slug);
}
